CREATE OR REPLACE FUNCTION public.create_new_user_rpc(new_email text, new_password text, new_role text)
 RETURNS json
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
declare
  creator_id uuid;
  creator_profile record;
  target_org_id uuid;
  new_user_id uuid;
  encrypted_pw text;
  v_instance_id uuid; -- <--- VARIABLE PARA GUARDAR EL ID REAL DEL PROYECTO
begin
  -- 1. Identificar al creador y SU INSTANCE_ID
  creator_id := auth.uid();
  if creator_id is null then
    raise exception 'No autenticado';
  end if;

  -- ðŸ•µï¸â€â™‚ï¸ OBTENER EL INSTANCE_ID REAL DEL PROYECTO
  select instance_id into v_instance_id from auth.users where id = creator_id;

  if v_instance_id is null then
     -- Fallback por si acaso (aunque no deberÃ­a pasar en cloud)
     v_instance_id := '00000000-0000-0000-0000-000000000000';
  end if;

  -- 2. Obtener datos del perfil del creador
  select * into creator_profile from public.profiles where id = creator_id;
  if creator_profile is null then
    raise exception 'Perfil del creador no encontrado';
  end if;

  -- 3. LÃ³gica "Smart Provisioning"
  if new_role = 'leader' then
    insert into public.organizations (name, slug)
    values ('Departamento - ' || split_part(new_email, '@', 1), gen_random_uuid()::text)
    returning id into target_org_id;
  else
    if creator_profile.org_id is null then
      raise exception 'El creador no pertenece a ninguna organizaciÃ³n para heredar.';
    end if;
    target_org_id := creator_profile.org_id;
  end if;

  -- 4. Generar ID y Password
  new_user_id := gen_random_uuid();
  encrypted_pw := crypt(new_password, gen_salt('bf'));

  -- 5. Insertar en auth.users (USANDO EL INSTANCE_ID REAL)
  insert into auth.users (
    instance_id, -- <--- AQUÃ USAMOS LA VARIABLE
    id,
    aud,
    role,
    email,
    encrypted_password,
    email_confirmed_at,
    raw_user_meta_data,
    created_at,
    updated_at
  ) values (
    v_instance_id, -- <--- CORRECTO
    new_user_id,
    'authenticated',
    'authenticated',
    new_email,
    encrypted_pw,
    now(),
    jsonb_build_object('role', new_role),
    now(),
    now()
  );

  -- 6. Insertar en auth.identities
  insert into auth.identities (
    id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at
  ) values (
    gen_random_uuid(),
    new_user_id,
    new_email,
    jsonb_build_object('sub', new_user_id, 'email', new_email, 'email_verified', true, 'phone_verified', false),
    'email',
    now(), now(), now()
  );

  -- 7. Insertar en public.profiles
  begin
    insert into public.profiles (id, email, role, org_id, display_name)
    values (
      new_user_id,
      new_email,
      new_role::public.app_role,
      target_org_id,
      split_part(new_email, '@', 1)
    );
  exception when unique_violation then
    update public.profiles
    set org_id = target_org_id,
        role = new_role::public.app_role
    where id = new_user_id;
  end;

  return json_build_object(
    'message', 'Usuario creado exitosamente (v3.0 - Instance ID Fix)',
    'id', new_user_id,
    'org_id', target_org_id
  );
end;
$function$
;

CREATE OR REPLACE FUNCTION public.delete_user_cascade(target_user_id uuid)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
  caller_id uuid;
  caller_role text;
  target_profile record;
  sub_profile record;
BEGIN
  caller_id := auth.uid();
  IF caller_id IS NULL THEN RAISE EXCEPTION 'No autenticado'; END IF;

  SELECT role INTO caller_role FROM public.profiles WHERE id = caller_id;
  SELECT * INTO target_profile FROM public.profiles WHERE id = target_user_id;

  IF target_profile IS NULL THEN RAISE EXCEPTION 'Usuario no encontrado'; END IF;

  -- Solo el owner directo o super_admin pueden eliminar
  IF caller_role != 'super_admin' AND target_profile.owner_id != caller_id THEN
    RAISE EXCEPTION 'No tienes permisos para eliminar este usuario';
  END IF;

  -- Proteger cuenta maestra
  IF target_profile.email = 'admin@genesis.com' THEN
    RAISE EXCEPTION 'No se puede eliminar la cuenta maestra';
  END IF;

  -- Recursividad: eliminar subordinados primero
  FOR sub_profile IN SELECT * FROM public.profiles WHERE owner_id = target_user_id
  LOOP
    PERFORM delete_user_cascade(sub_profile.id);
  END LOOP;

  -- Solo borrar datos de la org si es lÃ­der o pastor (NO si es cajero/cocina)
  -- Borrar un cajero no debe eliminar el inventario del lÃ­der
  IF target_profile.org_id IS NOT NULL AND target_profile.role NOT IN ('cashier', 'kitchen') THEN
    DELETE FROM public.order_items WHERE order_id IN (
      SELECT id FROM public.orders WHERE org_id = target_profile.org_id
    );
    DELETE FROM public.orders WHERE org_id = target_profile.org_id;
    DELETE FROM public.products WHERE org_id = target_profile.org_id;
  END IF;

  -- Eliminar perfil
  DELETE FROM public.profiles WHERE id = target_user_id;

  -- Limpiar org fantasma
  IF target_profile.org_id IS NOT NULL THEN
    DELETE FROM public.organizations WHERE id = target_profile.org_id
      AND NOT EXISTS (SELECT 1 FROM public.profiles WHERE org_id = target_profile.org_id);
  END IF;

  -- Liberar email para reuso
  DELETE FROM auth.users WHERE id = target_user_id;
END;
$function$
;

