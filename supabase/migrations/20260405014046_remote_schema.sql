CREATE OR REPLACE FUNCTION public.provision_user_profile(target_user_id uuid, user_email text, user_role text)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
  creator_id uuid;
  creator_profile record;
  target_org_id uuid;
BEGIN
  creator_id := auth.uid();
  IF creator_id IS NULL THEN
    RAISE EXCEPTION 'No autenticado';
  END IF;

  SELECT * INTO creator_profile FROM public.profiles WHERE id = creator_id;
  IF creator_profile IS NULL THEN
    RAISE EXCEPTION 'Perfil del creador no encontrado';
  END IF;

  -- Pastor y Leader = OrganizaciÃ³n PROPIA (aislamiento total)
  IF user_role IN ('leader', 'pastor') THEN
    INSERT INTO public.organizations (name, slug)
    VALUES (
      CASE user_role
        WHEN 'pastor' THEN 'Iglesia - ' || split_part(user_email, '@', 1)
        WHEN 'leader' THEN 'Departamento - ' || split_part(user_email, '@', 1)
      END,
      gen_random_uuid()::text
    )
    RETURNING id INTO target_org_id;
  ELSE
    -- Staff (cashier, kitchen) = Hereda la org del creador
    IF creator_profile.org_id IS NULL THEN
      RAISE EXCEPTION 'El creador no pertenece a ninguna organizaciÃ³n para heredar.';
    END IF;
    target_org_id := creator_profile.org_id;
  END IF;

  INSERT INTO public.profiles (id, email, role, org_id, display_name, onboarding_completed)
  VALUES (
    target_user_id,
    user_email,
    user_role::public.app_role,
    target_org_id,
    split_part(user_email, '@', 1),
    true
  )
  ON CONFLICT (id) DO UPDATE
  SET role = excluded.role,
      org_id = excluded.org_id,
      onboarding_completed = true;
END;
$function$
;

